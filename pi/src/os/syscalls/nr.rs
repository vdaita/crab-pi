//! ARM EABI syscall numbers (arch/arm/tools/syscall.tbl). Not every number
//! here has a handler; the extras are listed so traces and "unimplemented"
//! messages can name them.
#![allow(dead_code)]

macro_rules! syscall_numbers {
    ($($name:ident = $nr:expr,)*) => {
        paste::paste! { $(pub const [<$name:upper>]: u32 = $nr;)* }

        pub fn name(nr: u32) -> &'static str {
            match nr {
                $($nr => stringify!($name),)*
                _ => "?",
            }
        }
    };
}

